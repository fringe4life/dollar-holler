import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  MONEY_GLYPHS,
  MONEY_UNICODE_RANGE,
} from "../src/lib/fonts/money-glyphs.ts";

const require = createRequire(import.meta.url);

type SubsetFont = (
  source: Buffer,
  text: string,
  options: { targetFormat: "woff2" }
) => Promise<Buffer>;

const subsetFont = require("subset-font") as SubsetFont;

const WEIGHTS = [400, 700] as const;
const PACKAGE_ROOT = dirname(
  require.resolve("@fontsource/space-mono/package.json")
);
const SOURCE_DIR = join(PACKAGE_ROOT, "files");
const OUT_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/lib/fonts/money"
);

const cssForWeight = (
  weight: (typeof WEIGHTS)[number]
): string => `/* space-mono-latin-${weight}-normal (money glyphs) */
@font-face {
  font-display: swap;
  font-family: "Space Mono";
  font-style: normal;
  font-weight: ${weight};
  src: url("./space-mono-${weight}.woff2") format("woff2");
  unicode-range:
    ${MONEY_UNICODE_RANGE};
}
`;

await mkdir(OUT_DIR, { recursive: true });

const cssChunks = [
  `/* Generated by \`bun run fonts:subset-money\`. Do not edit by hand. */`,
];

for (const weight of WEIGHTS) {
  const sourceName = `space-mono-latin-${weight}-normal.woff2`;
  const sourcePath = join(SOURCE_DIR, sourceName);
  const sourceBuffer = await readFile(sourcePath);
  const subsetBuffer = await subsetFont(
    Buffer.from(sourceBuffer),
    MONEY_GLYPHS,
    {
      targetFormat: "woff2",
    }
  );
  const outPath = join(OUT_DIR, `space-mono-${weight}.woff2`);
  await writeFile(outPath, subsetBuffer);
  const saved = 1 - subsetBuffer.byteLength / sourceBuffer.byteLength;
  console.log(
    `${sourceName}: ${sourceBuffer.byteLength} → ${subsetBuffer.byteLength} bytes (${(saved * 100).toFixed(1)}% smaller)`
  );
  cssChunks.push(cssForWeight(weight));
}

await writeFile(join(OUT_DIR, "money.css"), `${cssChunks.join("\n")}\n`);
console.log(`unicode-range: ${MONEY_UNICODE_RANGE}`);
